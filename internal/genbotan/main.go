// Command genbotan writes testdata/botan-diff.vec, a differential corpus of
// Twofish single-block vectors produced by the installed Botan command line
// (`botan cipher --cipher=Twofish/CBC/NoPadding` with a zero IV, which on one
// block is plain ECB). Key sizes cycle through 16, 24 and 32 bytes. Keys and
// blocks come from a fixed-seed PRNG, so a rerun with the same Botan rewrites
// the same file.
//
// Usage: go run ./internal/genbotan [-n 600] [-o testdata/botan-diff.vec]
package main

import (
	"bytes"
	"encoding/hex"
	"fmt"
	"io"
	"math/rand/v2"
	"os"
	"os/exec"
	"path/filepath"

	"github.com/spf13/cobra"
)

var osExit = os.Exit

// run asks botan to encrypt one block; it is a variable so tests can fake it.
var run = func(key, block []byte) ([]byte, error) {
	dir, err := os.MkdirTemp("", "genbotan")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(dir)
	in := filepath.Join(dir, "in")
	if err := os.WriteFile(in, block, 0o600); err != nil {
		return nil, err
	}
	cmd := exec.Command("botan", "cipher", "--cipher=Twofish/CBC/NoPadding",
		"--key="+hex.EncodeToString(key), "--nonce="+hex.EncodeToString(make([]byte, 16)), in)
	cmd.Stdin = nil
	return cmd.Output()
}

func generate(w io.Writer, n int) error {
	r := rand.New(rand.NewPCG(1, 2))
	fmt.Fprintln(w, "# Generated by internal/genbotan from the Botan command line; do not edit.")
	fmt.Fprintln(w, "[Twofish]")
	for i := 0; i < n; i++ {
		key, block := make([]byte, 16+8*(i%3)), make([]byte, 16)
		for j := range key {
			key[j] = byte(r.Uint32())
		}
		for j := range block {
			block[j] = byte(r.Uint32())
		}
		// Edge cases first: all-zero and all-one key bytes of each size.
		switch {
		case i < 3:
			clear(key)
		case i < 6:
			for j := range key {
				key[j] = 0xff
			}
		}
		out, err := run(key, block)
		if err != nil {
			return err
		}
		if len(out) != 16 {
			return fmt.Errorf("botan returned %d bytes, want 16", len(out))
		}
		fmt.Fprintf(w, "\nKey = %X\nIn = %X\nOut = %X\n", key, block, out)
	}
	return nil
}

// RootCmd builds the command.
func RootCmd() *cobra.Command {
	var n int
	var out string
	cmd := &cobra.Command{
		Use:          "genbotan",
		Short:        "write the Botan differential corpus for Twofish",
		SilenceUsage: true,
		Args:         cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			var buf bytes.Buffer
			if err := generate(&buf, n); err != nil {
				return err
			}
			if err := os.WriteFile(out, buf.Bytes(), 0o644); err != nil {
				return err
			}
			fmt.Fprintf(cmd.OutOrStdout(), "wrote %d vectors to %s\n", n, out)
			return nil
		},
	}
	cmd.Flags().IntVarP(&n, "count", "n", 600, "number of vectors")
	cmd.Flags().StringVarP(&out, "output", "o", "testdata/botan-diff.vec", "output file")
	return cmd
}

func main() {
	if err := RootCmd().Execute(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		osExit(1)
	}
}
